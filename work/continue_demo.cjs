const fs=require('fs'), path=require('path'), crypto=require('crypto');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'work','demo'),app=path.join(root,'fraud-investigation');
process.env.PLAYWRIGHT_BROWSERS_PATH=path.join(root,'work','recording-tools','browsers');
const {chromium}=require('./recording-tools/node_modules/playwright');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const digest=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
(async()=>{
  const old=JSON.parse(fs.readFileSync(path.join(dir,'recording-metadata.json'),'utf8'));
  fs.copyFileSync(path.join(dir,'recording-metadata.json'),path.join(dir,'recording-attempt-1.json'));
  fs.renameSync(path.join(dir,'browser-recording.webm'),path.join(dir,'browser-recording-part1.webm'));
  const human=old.chapter_marks.find(x=>x.title.startsWith('6 / 7'));
  const prefixEnd=human.start_seconds+7.5;
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1600,height:1000},recordVideo:{dir:path.join(dir,'raw-part2'),size:{width:1600,height:1000}},reducedMotion:'reduce'});
  const token=fs.readFileSync(path.join(app,'.tools','analyst-demo.token'),'utf8').trim();
  await context.addInitScript(({token})=>sessionStorage.setItem('fraudinv.analystToken',token),{token});
  const page=await context.newPage();page.setDefaultTimeout(20000);
  const start=Date.now();let trimStart=0;
  const meta={...old,completed:false,error:null,capture_edit:'Chapter cut after start-review; capture harness selector corrected. No AI response or app result was regenerated.',source_clips:{prefix_end:prefixEnd}};
  const mark=(title,detail)=>{
    const sec=prefixEnd+(Date.now()-start)/1000-trimStart;
    meta.chapter_marks.push({start_seconds:sec,title,detail});
    console.log(JSON.stringify({chapter:title,seconds:Math.round(sec)}));
  };
  const show=async l=>{await l.evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));await page.evaluate(()=>window.scrollBy(0,-75));await pause(1000);};
  try{
    await page.goto('http://127.0.0.1:8765/#/case/'+encodeURIComponent(meta.case_id),{waitUntil:'networkidle'});
    await page.locator('.actions select').waitFor();
    await show(page.getByRole('heading',{name:'Review action',exact:true}));
    trimStart=(Date.now()-start)/1000;meta.source_clips.continuation_start=trimStart;
    mark('A HUMAN DISPOSITION, RECORDED EXPLICITLY','Review is in progress. The analyst chooses “needs more information” without asserting a fraud outcome.');
    await pause(2500);
    await page.locator('.actions select').selectOption('needs_more_information');
    await pause(2500);
    const response=page.waitForResponse(r=>r.url().endsWith('/transition')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Close with disposition',exact:true}).click();
    if(!(await response).ok())throw new Error('Close failed');
    await page.getByText('Closed cases cannot be reopened in this demo.',{exact:true}).waitFor();
    await pause(3000);
    await show(page.getByRole('heading',{name:'Audit trail',exact:true}));
    mark('AN APPEND-ONLY REVIEW TRAIL','The audit records the human actor, the previous state and the closed case disposition.');
    await pause(12000);
    await page.screenshot({path:path.join(dir,'audit-trail.png'),fullPage:true});
    meta.evidence_after_review=await page.evaluate(async id=>(await fetch('/cases/'+id+'/evidence')).json(),meta.case_id);
    await page.getByRole('link',{name:'Overview',exact:true}).click();
    await page.getByText('Replay runs',{exact:true}).waitFor();
    await page.evaluate(()=>window.scrollTo(0,0));
    mark('7 / 7  •  REPRODUCIBLE, WITH HONEST LIMITS','101 tests pass. Fresh assistant holdout: 10/12; its two documented failures produced no unsafe delivered output.');
    await pause(17000);
    mark('KNOWN ASSISTANT LIMITATIONS','Question-number filtering, refusal grading and short note paraphrases need further work. A small holdout is not a universal safety claim.');
    await pause(14000);
    meta.duration_seconds=prefixEnd+(Date.now()-start)/1000-trimStart;
    meta.completed=true;
  }catch(e){meta.error=String(e.stack||e);console.error(e)}
  const video=page.video();await context.close();await video.saveAs(path.join(dir,'browser-recording-part2.webm'));await browser.close();
  meta.protected_report_hashes_after=Object.fromEntries(Object.keys(meta.protected_report_hashes_before).map(f=>[f,digest(path.join(app,'reports','day6',f))]));
  meta.protected_reports_unchanged=JSON.stringify(meta.protected_report_hashes_before)===JSON.stringify(meta.protected_report_hashes_after);
  fs.writeFileSync(path.join(dir,'recording-metadata.json'),JSON.stringify(meta,null,2));
  console.log(JSON.stringify({completed:meta.completed,duration_seconds:meta.duration_seconds,protected_reports_unchanged:meta.protected_reports_unchanged}));
  if(!meta.completed)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
