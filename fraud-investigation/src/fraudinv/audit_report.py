"""Render the machine-readable audit as a readable Markdown summary."""
from __future__ import annotations

from pathlib import Path


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.3f}%"


def _table(rows: list[dict], cols: list[str], fmt: dict | None = None) -> str:
    fmt = fmt or {}
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c)
            cells.append(fmt[c](v) if c in fmt else (f"{v:,}" if isinstance(v, int) else str(v)))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def write_markdown(r: dict, path: Path) -> None:
    t, d = r["typed_checks"], r["duplicates"]
    raw = r["raw_text_checks"]
    lines = [
        "# Day 1 data-quality audit (generated)",
        "",
        f"Generated by `python -m fraudinv audit`. Split protocol `{r['contract_versions']['split']}`, "
        f"feature contract `{r['contract_versions']['features']}`. No model was trained or scored.",
        "",
        "## Source verification",
    ]
    for name, v in r.get("source_verification", {}).items():
        lines.append(f"- {name}: {v['bytes']:,} bytes, sha256 `{v['sha256']}` — verified={v['verified']}")
    ii = r["ingest_integrity"]
    lines.append(f"- Parquet `source_row` re-checked against original CSV lines "
                 f"{[c['source_row'] for c in ii['checked']]}: passed={ii['passed']}")
    lines += ["", "## Values and domains",
              f"- Rows {t['rows']:,}; distinct source_row {t['distinct_source_rows']:,} (max {t['max_source_row']:,}).",
              f"- Steps {t['min_step']}–{t['max_step']}, {t['observed_steps']} observed; out of range: {t['step_out_of_range']}.",
              f"- Unknown transaction types: {t['type_out_of_domain']}; malformed account IDs: "
              f"orig {t['nameOrig_bad_format']}, dest {t['nameDest_bad_format']}; self-transfers: {t['self_transfer_rows']}.",
              f"- Labels outside 0/1: isFraud {raw['isFraud_outside_01']}, isFlaggedFraud {raw['isFlaggedFraud_outside_01']}; "
              f"non-integer steps {raw['step_not_integer']}; empty strings {raw['empty_strings']}.",
              f"- Policy flag: {t['policy_flagged']} flagged; {t['flagged_and_positive']} also labelled positive, "
              f"{t['flagged_and_negative']} labelled negative.", "",
              "| field | unparseable text | nan/inf text | NaN | ±inf | null | negative | zero | "
              "scientific-notation text | max effective decimals |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for c in ["amount", "oldbalanceOrg", "newbalanceOrig", "oldbalanceDest", "newbalanceDest"]:
        lines.append(f"| {c} | {raw[c + '_unparseable']} | {raw[c + '_nan_inf_text']} | {t[c + '_nan']} | "
                     f"{t[c + '_inf']} | {t[c + '_null']} | {t[c + '_negative']:,} | {t[c + '_zero']:,} | "
                     f"{raw[c + '_scientific_notation']:,} | {raw[c + '_max_decimals']} |")
    lines += ["", "Numbers at or above 10,000,000 are written in Java scientific notation in the source "
                  "(e.g. `4.196370815E7`); effective decimals are counted after expanding the exponent."]
    lines += ["", "Zero amounts by type/class:", "",
              _table(t["zero_amount_by_type_and_class"], ["type", "isFraud", "rows"]),
              "", "Account prefixes by role/type:", "",
              _table(t["name_prefix_by_role_and_type"], ["type", "orig_prefix", "dest_prefix", "rows", "positives"])]
    ex, kc, tc = d["exact_all_columns"], d["same_step_type_amount_sender_recipient"], d["positive_transfer_cashout_pairing"]
    lines += ["", "## Duplicates",
              f"- Exact duplicates across all 11 source columns: {ex['duplicate_groups']} groups, "
              f"{ex['rows_in_groups']} rows ({ex['surplus_rows']} surplus).",
              f"- Same non-label values with conflicting labels: {d['same_non_label_values_different_label']['groups_with_conflicting_labels']} groups.",
              f"- Same (step, type, amount, sender, recipient): {kc['duplicate_groups']} groups, "
              f"{kc['rows_in_groups']} rows, {kc['positives_in_groups']} positives.",
              f"- Positive TRANSFER rows {tc['positive_transfers']:,}; positive CASH_OUT rows {tc['positive_cash_outs']:,}; "
              f"same-step same-amount TRANSFER/CASH_OUT positive pairs {tc['same_step_same_amount_pairs']:,}; "
              f"TRANSFER recipient equal to CASH_OUT sender {tc['transfer_dest_equals_cashout_orig']:,}."]
    ps = r["partition_support"]
    lines += ["", "## Frozen partitions — class support", "",
              _table(ps["by_partition"], ["partition", "first_step", "last_step", "observed_hours", "rows",
                                          "positives", "prevalence", "policy_flagged", "days_touched"],
                     {"prevalence": _pct}),
              "", _table(ps["by_partition_type"], ["partition", "type", "rows", "positives", "policy_flagged"])]
    rh = r["recipient_history"]
    o = rh["overall"]
    lines += ["", "## Recipient-history coverage (strictly earlier steps)",
              f"Definition: {rh['definition']}.",
              f"- Overall: {o['with_prior']:,} of {o['rows']:,} rows ({_pct(o['with_prior'] / o['rows'])}) have earlier-step "
              f"recipient history; {o['with_prior_24h']:,} ({_pct(o['with_prior_24h'] / o['rows'])}) within 24 steps.",
              "", _table(rh["by_partition_label"], ["partition", "label", "rows", "with_prior_fraction",
                                                    "with_prior_24h_fraction"],
                         {"with_prior_fraction": _pct, "with_prior_24h_fraction": _pct}),
              "", _table(rh["by_partition_type_label"],
                         ["partition", "type", "label", "rows", "with_prior", "with_prior_fraction",
                          "with_prior_24h_fraction", "same_step_only_recurrence", "prior_1", "prior_2_4",
                          "prior_5_9", "prior_10_plus", "dest_seen_earlier_as_sender"],
                         {"with_prior_fraction": _pct, "with_prior_24h_fraction": _pct}),
              "", "Sender history (retained limitation):", "",
              _table(rh["sender_history_by_partition"], ["partition", "rows", "with_prior", "with_prior_fraction",
                                                         "positives_with_prior"], {"with_prior_fraction": _pct})]
    hc = r["history_crosscheck"]
    lines += ["", f"DuckDB vs pandas reference history cross-check on steps {hc['steps']}: {hc['rows']:,} rows, "
                  f"{hc['mismatch_prior_count']} all-history mismatches, {hc['mismatch_prior_24h']} 24-step mismatches "
                  f"— passed={hc['passed']}."]
    pp = r["pure_positive_hours"]
    lines += ["", "## Pure-positive hours (evaluator-only diagnostic)", "",
              _table(pp["by_partition"], ["partition", "observed_hours", "pure_positive_hours", "positives_in_pure_hours",
                                          "mixed_hours", "positives_in_mixed_hours", "rows_in_mixed_hours",
                                          "zero_positive_hours", "positives"]),
              "", _table(pp["pure_hour_row_counts"], ["partition", "min_rows", "median_rows", "max_rows"]),
              "", "Pure-positive hours by hour of day ((step-1) mod 24):", "",
              _table(pp["by_hour_of_day"], ["hour_of_day", "observed_hours", "pure_positive_hours", "rows", "positives"])]
    rt = r["runtime"]
    env = r["environment"]
    lines += ["", "## Runtime",
              f"- Total {rt['total_seconds']}s; sections: " + ", ".join(f"{k} {v}s" for k, v in rt["sections_seconds"].items()),
              f"- Peak Python process working set {rt['peak_python_process_mib']} MiB (DuckDB limit {rt['duckdb_memory_limit']}, "
              f"{rt['duckdb_threads']} threads).",
              f"- Python {env['python']} on {env['platform']}; RAM {env.get('total_gib')} GiB total, "
              f"{env.get('available_gib')} GiB available at start.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
