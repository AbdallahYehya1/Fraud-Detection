"""Local PostgreSQL access, roles and migrations.

Three roles keep truth isolated:

* ``fraudinv_admin`` - container superuser; runs migrations only.
* ``fraudinv_app``   - serving, replay and case workflow. No privilege on schema ``truth``.
* ``fraudinv_eval``  - offline evaluation; reads ``app`` and ``truth``.
"""
from __future__ import annotations

import os
import secrets
from pathlib import Path

import psycopg
from psycopg import sql

from .config import APP_ROOT

ENV_FILE = APP_ROOT / ".env"
SQL_DIR = APP_ROOT / "sql"
ROLES = {"admin": "fraudinv_admin", "app": "fraudinv_app", "eval": "fraudinv_eval"}


def load_env(path: Path = ENV_FILE) -> dict[str, str]:
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    values.update({k: v for k, v in os.environ.items() if k.startswith("FRAUDINV_DB_")})
    return values


def write_env(path: Path = ENV_FILE) -> bool:
    """Create .env with random local passwords. Never overwrites an existing file."""
    if path.exists():
        return False
    lines = ["# Local-only database credentials (git-ignored). Generated by `python -m fraudinv db-env`.",
             "FRAUDINV_DB_HOST=127.0.0.1", "FRAUDINV_DB_PORT=55432", "FRAUDINV_DB_NAME=fraudinv"]
    for role in ROLES:
        lines.append(f"FRAUDINV_DB_{role.upper()}_PASSWORD={secrets.token_urlsafe(24)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


def conninfo(role: str = "app", dbname: str | None = None) -> str:
    env = load_env()
    return psycopg.conninfo.make_conninfo(
        host=env.get("FRAUDINV_DB_HOST", "127.0.0.1"), port=env.get("FRAUDINV_DB_PORT", "55432"),
        dbname=dbname or env.get("FRAUDINV_DB_NAME", "fraudinv"), user=ROLES[role],
        password=env[f"FRAUDINV_DB_{role.upper()}_PASSWORD"], connect_timeout=5)


def connect(role: str = "app", dbname: str | None = None, **kw) -> psycopg.Connection:
    return psycopg.connect(conninfo(role, dbname), **kw)


def ensure_roles(admin: psycopg.Connection) -> None:
    env = load_env()
    for role in ("app", "eval"):
        name = ROLES[role]
        pw = env[f"FRAUDINV_DB_{role.upper()}_PASSWORD"]
        exists = admin.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (name,)).fetchone()
        verb = "ALTER" if exists else "CREATE"
        admin.execute(sql.SQL("{} ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD {}").format(
            sql.SQL(verb), sql.Identifier(name), sql.Literal(pw)))


GRANTS = """
GRANT CONNECT ON DATABASE {db} TO fraudinv_app, fraudinv_eval;
GRANT USAGE ON SCHEMA app TO fraudinv_app, fraudinv_eval;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA app TO fraudinv_app;
GRANT DELETE ON app.recipient_step_count TO fraudinv_app;
REVOKE UPDATE ON app.audit_event, app.transaction_event, app.score, app.alert,
                 app.day_finalization, app.case_note FROM fraudinv_app;
REVOKE INSERT, UPDATE ON app.analyst FROM fraudinv_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO fraudinv_app;
GRANT SELECT ON ALL TABLES IN SCHEMA app TO fraudinv_eval;
GRANT USAGE ON SCHEMA truth TO fraudinv_eval;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA truth TO fraudinv_eval;
REVOKE ALL ON SCHEMA truth FROM fraudinv_app;
"""


def migrate(dbname: str | None = None) -> list[str]:
    """Apply sql/*.sql in order once each, then (re)apply roles and grants."""
    applied = []
    env = load_env()
    db = dbname or env.get("FRAUDINV_DB_NAME", "fraudinv")
    with connect("admin", db, autocommit=True) as admin:
        ensure_roles(admin)
        admin.execute("CREATE TABLE IF NOT EXISTS public.schema_migration ("
                      "name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())")
        done = {r[0] for r in admin.execute("SELECT name FROM public.schema_migration").fetchall()}
        for path in sorted(SQL_DIR.glob("*.sql")):
            if path.name in done:
                continue
            with admin.transaction():
                admin.execute(path.read_text(encoding="utf-8"))
                admin.execute("INSERT INTO public.schema_migration (name) VALUES (%s)", (path.name,))
            applied.append(path.name)
        admin.execute(GRANTS.format(db=sql.Identifier(db).as_string(admin)))
    return applied


def create_database(name: str) -> bool:
    with connect("admin", "postgres", autocommit=True) as admin:
        if admin.execute("SELECT 1 FROM pg_database WHERE datname = %s", (name,)).fetchone():
            return False
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
        return True


def drop_database(name: str) -> None:
    if name == load_env().get("FRAUDINV_DB_NAME", "fraudinv"):
        raise ValueError("refusing to drop the main application database")
    with connect("admin", "postgres", autocommit=True) as admin:
        admin.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))
